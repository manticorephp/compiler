<?php
// strtotime on ISO date/datetime strings, in several zones, with a fixed base
$strs = ['2024-01-15', '2024-01-15 10:00:00', '2024-01-15 10:00', '2024-01-15T10:00:00', '2024-1-5 9:05', '2024-01-15  10:00:07',
         ' 2024-01-15 10:00:00 ', '2024-02-29 23:59:59', '2023-02-29', '2024-01-15 24:00:00',
         '2024-01-15 10:00:00.5', '2024-01-15 10:00 pm', '2024-01-15 10:00:00 +02:00', '2024-01-15 10:00:00 UTC', '2024-01-15 10:00:00 Europe/Kyiv',
         '2024-03-10 02:30:00', '2024-03-31 03:30:00', '2024-10-27 03:30:00', '2024-11-03 01:30:00', '1970-01-01 00:00:00', '1969-12-31 23:59:59',
         '0001-01-01', '9999-12-31 23:59:59', '2024-01-15 10:00:00 +1 day', '2024-01-15 garbage', '', 'garbage', '2024-01-1510:00'];
foreach (['UTC', 'Europe/Kyiv', 'America/New_York', 'Asia/Kolkata'] as $tz) {
    date_default_timezone_set($tz);
    echo $tz, "\n";
    foreach ($strs as $s) {
        $t = strtotime($s, 1700000000);
        echo '  ', bin2hex($s), ' ', var_export($t, true), ' ', $t === false ? '-' : date('c', $t), "\n";
    }
}
