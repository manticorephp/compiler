set_error_handler(function ($n, $s) { if (!(error_reporting() & $n)) { return false; } echo "WARN: $s\n"; return true; });
function pdo(int $mode = PDO::ERRMODE_EXCEPTION, array $o = []): PDO { return new PDO((string) getenv('PDO_MY_DSN'), getenv('PDO_USER') ?: 'u', getenv('PDO_PASS') ?: 'pw', $o + [PDO::ATTR_ERRMODE => $mode]); }
function t(string $label, callable $f): void {
    try { $r = var_export($f(), true); echo $label . ': ' . str_replace("\n", ' ', $r) . "\n"; }
    catch (PDOException $e) { echo $label . ': EXC ' . $e->getMessage() . ' ' . json_encode($e->errorInfo) . "\n"; }
}
