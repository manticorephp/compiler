function cnt(PDO $db): string { $s = $db->query('select count(*) from t'); return (string) $s->fetchColumn(); }
function t(string $label, callable $f): void {
    try { $r = var_export($f(), true); echo $label . ': ' . $r . "\n"; }
    catch (PDOException $e) { echo $label . ': EXC ' . $e->getMessage() . ' ' . json_encode($e->errorInfo) . "\n"; }
    catch (TypeError $e) { echo $label . ': TypeError ' . $e->getMessage() . "\n"; }
}
