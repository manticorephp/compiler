<?php
// Build-time step for the AOT binary: turns Blade's compiled views (view:cache) into plain
// functions `aot_v_<hash>(array $__data): string`, so no `include`/`extract` is needed at run time.
// Run with the Zend `php` before `manticore build`:   php aot/compile-views.php
$root = dirname(__DIR__);
require $root . '/vendor/autoload.php';
$app = require $root . '/bootstrap/app.php';
$app->make(Illuminate\Contracts\Console\Kernel::class)->bootstrap();
$blade = app('blade.compiler');
$files = app('files');
$outDir = $root . '/app/AotViews';
is_dir($outDir) || mkdir($outDir, 0777, true);
foreach (glob($outDir . '/*.php') as $old) { unlink($old); }

// every view the app can reach: its own, plus the framework / package ones registered in the finder
$sources = [];
foreach (config('view.paths') as $p) {
    foreach ($files->allFiles($p) as $f) { if (str_ends_with($f->getFilename(), '.blade.php')) { $sources[] = $f->getRealPath(); } }
}
$hints = app('view')->getFinder()->getHints();
foreach ($hints as $dirs) {
    foreach ($dirs as $d) {
        if (!is_dir($d)) { continue; }
        foreach ($files->allFiles($d) as $f) { if (str_ends_with($f->getFilename(), '.blade.php')) { $sources[] = $f->getRealPath(); } }
    }
}
$sources[] = $root . '/vendor/laravel/framework/src/Illuminate/Foundation/resources/health-up.blade.php';
$sources = array_values(array_unique($sources));

$aliases = Illuminate\Support\Facades\Facade::defaultAliases()->merge(config('app.aliases', []))->all();
$skip = ['_SERVER', '_GET', '_POST', '_COOKIE', '_FILES', '_REQUEST', '_SESSION', '_ENV', 'GLOBALS', 'this', '__data'];
$cases = [];
$skipped = [];
foreach ($sources as $src) {
    $blade->compile($src);
    $code = $files->get($blade->getCompiledPath($src));
    $rel = ltrim(substr($src, strlen($root)), '/');
    if (str_contains($code, '$$')) { $skipped[$rel] = 'variable variables'; continue; }
    // `@use` compiles to an inline open-tag `use X;` close-tag block: imports are per file, so hoist them.
    $uses = '';
    $code = preg_replace_callback('/<\?php\s+use\s+([^;]+);\s*\?>\n?/', function ($m) use (&$uses) { $uses .= 'use ' . trim($m[1]) . ";\n"; return ''; }, $code);
    // `Route::has()` in a view means the facade alias: AliasLoader's runtime `class_alias` does not exist in a native
    // binary, so spell the real class.
    $toks = token_get_all($code);
    $out = '';
    foreach ($toks as $i => $t) {
        if (is_array($t) && $t[0] === T_STRING && isset($aliases[$t[1]])) {
            $prev = $i > 0 ? $toks[$i - 1] : null;
            $j = $i + 1; while (isset($toks[$j]) && is_array($toks[$j]) && $toks[$j][0] === T_WHITESPACE) { $j++; }
            $next = $toks[$j] ?? null;
            $prevOk = !is_array($prev) || !in_array($prev[0], [T_NS_SEPARATOR, T_OBJECT_OPERATOR, T_DOUBLE_COLON, T_NEW, T_FUNCTION, T_CLASS], true);
            if ($prevOk && is_array($next) && $next[0] === T_DOUBLE_COLON) { $out .= '\\' . $aliases[$t[1]]; continue; }
        }
        $out .= is_array($t) ? $t[1] : $t;
    }
    $code = $out;
    $vars = [];
    $inHtml = true;
    foreach (token_get_all($code) as $t) {
        if (is_array($t)) {
            if ($t[0] === T_VARIABLE) { $n = substr($t[1], 1); if (!in_array($n, $skip, true)) { $vars[$n] = true; } }
            if ($t[0] === T_OPEN_TAG || $t[0] === T_OPEN_TAG_WITH_ECHO) { $inHtml = false; }
            if ($t[0] === T_CLOSE_TAG) { $inHtml = true; }
        }
    }
    unset($vars['__path']);
    $names = array_keys($vars);
    sort($names);
    // get_defined_vars() → the variables the template reads (what the frame would hold)
    $arr = '[' . implode(', ', array_map(fn ($n) => var_export($n, true) . ' => $' . $n, $names)) . ']';
    $code = str_replace('get_defined_vars()', $arr, $code);
    $fn = 'aot_v_' . substr(md5($rel), 0, 16);
    $pre = '';
    foreach ($names as $n) { $pre .= "    \$$n = \$__data['$n'] ?? null;\n"; }
    $body = $inHtml ? $code : $code . "\n?>";
    $php = "<?php\n// $rel\n$uses\nfunction $fn(array \$__data): string\n{\n$pre    ob_start();\n?>" . $body . "<?php\n    return (string) ob_get_clean();\n}\n";
    file_put_contents($outDir . '/' . $fn . '.php', $php);
    $cases[$rel] = $fn;
}
$sw = '';
foreach ($cases as $rel => $fn) { $sw .= "        case " . var_export($rel, true) . ": return $fn(\$data);\n"; }
file_put_contents($outDir . '/render.php', "<?php\n/** Generated by aot/compile-views.php — the precompiled view for a project-relative path, or null. */\nfunction aot_view_render(string \$rel, array \$data): ?string\n{\n    switch (\$rel) {\n$sw    }\n    return null;\n}\n");
echo count($cases), " views compiled, ", count($skipped), " skipped\n";
foreach ($skipped as $r => $why) { echo "  skipped ($why): $r\n"; }
