    /**
     * @param string[] $externFns lowercase names of the declare-only externs
     * @param array<string,bool> $userFiles absolute paths of the program's own sources
     * @param string[] $names callee as lowered
     * @param string[] $files
     * @param int[] $lines
     */
    public static function run(Module $m, \Compile\Diagnostics $d, array $externFns, array $userFiles, array $names, array $files, array $lines): void
    {
        $defined = [];
        foreach ($m->functions as $fn) {
            $defined[\strtolower($fn->name)] = true;
        }
        foreach ($externFns as $e) {
            $defined[$e] = true;
        }
        foreach (self::BUILTIN_NAMES as $b) {
            $defined[$b] = true;
        }
        $n = \count($names);
        for ($i = 0; $i < $n; $i = $i + 1) {
            if (!isset($userFiles[$files[$i]])) { continue; }
            $name = \ltrim($names[$i], '\\');
            $lc = \strtolower($name);
            if (isset($defined[$lc]) || \strncmp($lc, '__mir_', 6) === 0 || \strncmp($lc, '__mc_', 5) === 0) { continue; }
            $d->addUse('warning', 'undefined.function', $name, 'function ' . $name . '() is not declared', $files[$i], $lines[$i]);
        }
    }
