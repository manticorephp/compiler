/**
 * ext/tokenizer, scanner core.
 *
 * ⚠ THIS FILE NAMES NOTHING ZEND OWNS, ON PURPOSE. It can be `require`d under
 * plain `php`, which is what makes the differential harness possible: run
 * __McTok and Zend's C tokenizer inside the SAME interpreter and diff. A
 * divergence there is an ALGORITHM bug; a divergence that only shows up in the
 * compiled binary is a COMPILER bug. Keeping those two apart is worth more than
 * any single optimisation here, so do not move `PhpToken` / `token_get_all` /
