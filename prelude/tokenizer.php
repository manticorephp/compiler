 * allocation-free `__str_byte_at`. The char-local form needs a whole-function
 * proof, and one concat or argument use silently turns every byte read back
 * into a malloc — a 100 MB regression with no error. Never introduce one.
 *
 * The scanner fills four PARALLEL PACKED arrays. The heterogeneous
 * `array{int,string,int}|string` shape ext/tokenizer is specified in terms of is
 * built exactly once, at the API boundary, in the other file — never in here,
 * never per token.
 */

