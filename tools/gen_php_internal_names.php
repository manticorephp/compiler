<?php
declare(strict_types=1);

/**
 * Regenerates src/Compile/PhpInternalNames.php: the names PHP itself defines (functions, classes /
 * interfaces / traits / enums, constants), used to tell `unsupported.builtin` from `undefined.*`.
 *
 *   php -d xdebug.mode=off tools/gen_php_internal_names.php
 *
 * Same source of truth as tools/builtins_audit.php (the running php, minus the non-bundled
 * extensions): REGENERATE BOTH TOGETHER whenever the oracle php changes.
 */

$root = \dirname(__DIR__);
$nonBundled = ['xdebug', 'openswoole', 'zend opcache', 'mysqlnd'];

$fns = [];
foreach (\get_defined_functions()['internal'] as $f) {
    $ext = \strtolower((new \ReflectionFunction($f))->getExtensionName() ?: 'core');
    if (!\in_array($ext, $nonBundled, true)) { $fns[] = \strtolower($f); }
}
$classes = [];
foreach (\array_merge(\get_declared_classes(), \get_declared_interfaces(), \get_declared_traits()) as $c) {
    $ext = \strtolower((new \ReflectionClass($c))->getExtensionName() ?: 'core');
    if (!\in_array($ext, $nonBundled, true)) { $classes[] = \strtolower($c); }
}
$consts = [];
foreach (\get_defined_constants(true) as $ext => $list) {
    if ($ext === 'user' || \in_array(\strtolower((string)$ext), $nonBundled, true)) { continue; }
    foreach ($list as $n => $_) { $consts[] = (string)$n; }
}
foreach ([&$fns, &$classes, &$consts] as &$l) { $l = \array_values(\array_unique($l)); \sort($l); }
unset($l);

$blob = static fn(array $l): string => "'\n" . \implode("\n", $l) . "\n'";
$out = "<?php\n\nnamespace Compile;\n\n"
    . "/** GENERATED by tools/gen_php_internal_names.php (php " . PHP_VERSION . ") - do not edit; regenerate together with docs/builtins.md. */\n"
    . "final class PhpInternalNames\n{\n"
    . "    /** Newline-separated, lowercase. */\n    private const FUNCTIONS = " . $blob($fns) . ";\n\n"
    . "    /** Newline-separated, lowercase: classes, interfaces, traits, enums. */\n    private const CLASSES = " . $blob($classes) . ";\n\n"
    . "    /** Newline-separated, case-sensitive. */\n    private const CONSTANTS = " . $blob($consts) . ";\n\n"
    . "    public static function has(string \$kind, string \$name): bool\n    {\n"
    . "        \$name = \\ltrim(\$name, '\\\\');\n"
    . "        if (\$kind === 'constant') { return \\str_contains(self::CONSTANTS, \"\\n\" . \$name . \"\\n\"); }\n"
    . "        \$lc = \\strtolower(\$name);\n"
    . "        if (\$kind === 'function') { return \\str_contains(self::FUNCTIONS, \"\\n\" . \$lc . \"\\n\"); }\n"
    . "        return \\str_contains(self::CLASSES, \"\\n\" . \$lc . \"\\n\");\n    }\n}\n";
\file_put_contents($root . '/src/Compile/PhpInternalNames.php', $out);
\fprintf(STDERR, "functions %d, classes %d, constants %d\n", \count($fns), \count($classes), \count($consts));
